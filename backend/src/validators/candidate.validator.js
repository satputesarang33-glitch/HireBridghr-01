import { z } from 'zod';

export const createCandidateSchema = z.object({
  name: z.string().optional().nullable(),
  firstName: z.string().optional().nullable(),
  lastName: z.string().optional().nullable(),
  email: z.string().email('Valid email is required'),
  phone: z.string().optional().nullable(),
  location: z.string().optional().nullable(),
  currentTitle: z.string().optional().nullable(),
  company: z.string().optional().nullable(),
  skills: z.array(z.string()).optional().default([]),
  experienceYears: z.coerce.number().optional().nullable().default(0),
  rating: z.coerce.number().optional().nullable().default(5.0),
  status: z.string().optional().nullable().default('ACTIVE'),
  source: z.string().optional().nullable().default('Direct Sourcing'),
  tags: z.array(z.string()).optional().default([]),
  portfolioUrl: z.string().optional().nullable(),
  linkedinUrl: z.string().optional().nullable(),
  githubUrl: z.string().optional().nullable(),
  resumeUrl: z.string().optional().nullable(),
  resumeFileName: z.string().optional().nullable(),
  resumeFileSize: z.string().optional().nullable(),
  assignedRecruiterId: z.string().optional().nullable(),
  assignedRecruiterName: z.string().optional().nullable(),
  notes: z.any().optional().nullable(),
  timeline: z.any().optional().nullable(),
});

export const updateCandidateSchema = z.object({
  name: z.string().optional().nullable(),
  firstName: z.string().optional().nullable(),
  lastName: z.string().optional().nullable(),
  email: z.string().email().optional().nullable(),
  phone: z.string().optional().nullable(),
  location: z.string().optional().nullable(),
  currentTitle: z.string().optional().nullable(),
  company: z.string().optional().nullable(),
  skills: z.array(z.string()).optional(),
  experienceYears: z.coerce.number().optional().nullable(),
  rating: z.coerce.number().optional().nullable(),
  status: z.string().optional().nullable(),
  source: z.string().optional().nullable(),
  tags: z.array(z.string()).optional(),
  portfolioUrl: z.string().optional().nullable(),
  linkedinUrl: z.string().optional().nullable(),
  githubUrl: z.string().optional().nullable(),
  resumeUrl: z.string().optional().nullable(),
  resumeFileName: z.string().optional().nullable(),
  resumeFileSize: z.string().optional().nullable(),
  assignedRecruiterId: z.string().optional().nullable(),
  assignedRecruiterName: z.string().optional().nullable(),
  notes: z.any().optional().nullable(),
  timeline: z.any().optional().nullable(),
}).passthrough();

export const addCandidateNoteSchema = z.object({
  content: z.string().min(1, 'Note content cannot be empty'),
  rating: z.coerce.number().min(1).max(5).optional().nullable(),
  author: z.string().optional().nullable(),
  authorName: z.string().optional().nullable(),
});

